-- Create opportunities table
CREATE TABLE IF NOT EXISTS opportunities (
  id INT AUTO_INCREMENT PRIMARY KEY,
  title VARCHAR(255) NOT NULL,
  slug VARCHAR(255) UNIQUE,
  short_description TEXT,
  description LONGTEXT,
  category VARCHAR(100),
  organization_name VARCHAR(255),
  organization_logo VARCHAR(500),
  organization_website VARCHAR(500),
  opportunity_type ENUM('free', 'paid', 'affiliate') DEFAULT 'free',
  status ENUM('draft', 'published', 'expired', 'archived') DEFAULT 'draft',
  featured TINYINT(1) DEFAULT 0,
  image_url VARCHAR(500),
  country VARCHAR(100),
  city VARCHAR(100),
  location VARCHAR(255),
  remote TINYINT(1) DEFAULT 0,
  eligibility TEXT,
  requirements TEXT,
  benefits TEXT,
  application_instructions TEXT,
  application_url VARCHAR(500),
  application_email VARCHAR(255),
  application_open_date DATE,
  deadline DATE,
  expires_at DATE,
  published_at TIMESTAMP NULL,
  partner_name VARCHAR(255),
  partner_url VARCHAR(500),
  affiliate_url VARCHAR(500),
  affiliate_network VARCHAR(100),
  is_paid TINYINT(1) DEFAULT 0,
  price DECIMAL(10, 2),
  currency VARCHAR(10) DEFAULT 'KES',
  commission_type ENUM('none', 'percentage', 'fixed') DEFAULT 'none',
  commission_value DECIMAL(10, 2) DEFAULT 0,
  tags JSON,
  contact_name VARCHAR(255),
  contact_email VARCHAR(255),
  contact_phone VARCHAR(50),
  views INT DEFAULT 0,
  clicks INT DEFAULT 0,
  applications INT DEFAULT 0,
  review_status ENUM('not_reviewed', 'pending', 'approved', 'rejected') DEFAULT 'not_reviewed',
  review_notes TEXT,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_status (status),
  INDEX idx_category (category),
  INDEX idx_country (country),
  INDEX idx_opportunity_type (opportunity_type),
  INDEX idx_featured (featured),
  INDEX idx_deadline (deadline),
  INDEX idx_slug (slug),
  INDEX idx_created_at (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
